describe('msvcrt x87 trig (WMP 11)', () => {
  it('atan2: 64-bit results on integer pairs, stored doubles on the special arguments', () => {
    const o = new Float64Array(2);
    for (const r of ATAN2) {
      const [y, x, hi, lo] = r.split(' ') as [string, string, string, string];
      if (lo === 'd') { expect(atan2_32(d(y), d(x)), r).toBe(d(hi)); continue; }
      atan2Ext32(d(y), d(x), o);
      expect([o[0], o[1]], r).toEqual([d(hi), d(lo)]);
      expect(atan2_32(d(y), d(x)), r).toBe(d(hi) + d(lo));
    }
  });
  it('sin, cos, tan: stored doubles', () => {
    for (const r of TRIG) {
      const [x, s, c, t] = r.split(' ').map(d) as [number, number, number, number];
      expect([sin32(x), cos32(x), tan32(x)], r).toEqual([s, c, t]);
    }
  });
  it('Ext results are hi + lo with hi the stored double; f32Ext rounds the 64-bit value once', () => {
    const o = new Float64Array(2);
    sinExt32(1, o);
    expect(o[0]).toBe(sin32(1));
    expect(o[1]).not.toBe(0);                          // FSIN(1) carries bits below the double
    const tie = 1 + 2 ** -24;                          // halfway between two floats
    expect(f32Ext(tie, 2 ** -60)).toBe(1 + 2 ** -23);
    expect(f32Ext(tie, -(2 ** -60))).toBe(1);
    expect(f32Ext(tie, 0)).toBe(1);                    // a true tie: to even
  });
});
